export function detectLanguage(locale = 'en-US', mode = 'auto') {
  if (mode === 'zh' || mode === 'en') return mode;
  return /^zh(?:[-_]|$)/i.test(locale) ? 'zh' : 'en';
}

export function createI18n(language = 'en') {
  let current = detectLanguage(language, language);
  return {
    get language() { return current; },
    setLanguage(next) { current = detectLanguage(next, next); },
    t(key, values = {}) {
      const template = messages[current][key] || messages.en[key] || key;
      return template.replace(/\{(\w+)\}/g, (_match, name) => String(values[name] ?? ''));
    }
  };
}

export function translateElements(root, t) {
  for (const element of root.querySelectorAll('[data-i18n]')) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const attribute of ['title', 'aria-label', 'placeholder']) {
    for (const element of root.querySelectorAll(`[data-i18n-${attribute}]`)) {
      element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
    }
  }
}
